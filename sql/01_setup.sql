-- Run as ACCOUNTADMIN in a Snowsight worksheet.
USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS RETAIL_ROLE;
GRANT ROLE RETAIL_ROLE TO ROLE SYSADMIN;
SET me = CURRENT_USER();
GRANT ROLE RETAIL_ROLE TO USER IDENTIFIER($me);

-- Small warehouse that suspends after 60s idle
CREATE WAREHOUSE IF NOT EXISTS RETAIL_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

-- Cost guardrail: notify at 80% of 5 credits/month, suspend at 100%
CREATE OR REPLACE RESOURCE MONITOR RETAIL_MONITOR
  WITH CREDIT_QUOTA = 5 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 80 PERCENT DO NOTIFY ON 100 PERCENT DO SUSPEND;
ALTER WAREHOUSE RETAIL_WH SET RESOURCE_MONITOR = RETAIL_MONITOR;

CREATE DATABASE IF NOT EXISTS RETAIL_DB;
CREATE SCHEMA IF NOT EXISTS RETAIL_DB.BRONZE;
CREATE SCHEMA IF NOT EXISTS RETAIL_DB.SILVER;
CREATE SCHEMA IF NOT EXISTS RETAIL_DB.GOLD;

GRANT USAGE, OPERATE ON WAREHOUSE RETAIL_WH TO ROLE RETAIL_ROLE;
GRANT ALL ON DATABASE RETAIL_DB TO ROLE RETAIL_ROLE;
GRANT ALL ON ALL SCHEMAS IN DATABASE RETAIL_DB TO ROLE RETAIL_ROLE;
GRANT ALL ON FUTURE SCHEMAS IN DATABASE RETAIL_DB TO ROLE RETAIL_ROLE;
