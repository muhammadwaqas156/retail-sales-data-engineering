USE ROLE RETAIL_ROLE;
USE WAREHOUSE RETAIL_WH;
USE DATABASE RETAIL_DB;
USE SCHEMA BRONZE;

CREATE FILE FORMAT IF NOT EXISTS FF_CSV TYPE = CSV SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"' NULL_IF = ('') EMPTY_FIELD_AS_NULL = TRUE COMPRESSION = GZIP;
CREATE FILE FORMAT IF NOT EXISTS FF_NDJSON TYPE = JSON COMPRESSION = GZIP;

CREATE STAGE IF NOT EXISTS STG_RAW
  URL = 's3://<YOUR_BUCKET>/raw/' STORAGE_INTEGRATION = S3_RETAIL_INT;

LIST @STG_RAW;   -- should list your 4 uploaded files

-- Bronze = raw landing: everything as text, plus lineage columns
CREATE TABLE IF NOT EXISTS RAW_TRANSACTIONS (
  invoice STRING, stock_code STRING, description STRING, quantity STRING,
  invoice_date STRING, price STRING, customer_id STRING, country STRING, source_sheet STRING,
  _batch_id STRING, _source_file STRING, _file_row_number NUMBER,
  _loaded_at TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());

CREATE TABLE IF NOT EXISTS RAW_PRODUCTS (record VARIANT, _batch_id STRING, _source_file STRING, _file_row_number NUMBER, _loaded_at TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());
CREATE TABLE IF NOT EXISTS RAW_CARTS    (record VARIANT, _batch_id STRING, _source_file STRING, _file_row_number NUMBER, _loaded_at TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());
CREATE TABLE IF NOT EXISTS RAW_USERS    (record VARIANT, _batch_id STRING, _source_file STRING, _file_row_number NUMBER, _loaded_at TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());

CREATE TABLE IF NOT EXISTS LOAD_AUDIT (
  batch_id STRING, source STRING, file_name STRING, status STRING,
  rows_parsed NUMBER, rows_loaded NUMBER, errors_seen NUMBER, first_error STRING,
  loaded_at TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());
