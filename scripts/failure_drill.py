"""Failure and recovery drill. Produces evidence in docs/failure_recovery_evidence.md.

Runs the real pipeline scripts in an isolated temp data dir (DATA_DIR) and writes test objects
only under S3 prefix archive/drill/ (never raw/, so Snowflake never loads drill data).

Scenarios
  D1 missing extracts      -> validate_extracts must FAIL (exit 1)
  D2 valid extracts        -> validate_extracts must PASS (exit 0)
  D3 upload, bad bucket    -> upload must FAIL and the audit log must record status=failed
  D4 recovery, right bucket-> upload must succeed and audit shows status=uploaded
  D5 rerun (idempotency)   -> every file must be status=skipped_duplicate

Usage: python scripts/failure_drill.py        (needs S3_BUCKET and AWS_PROFILE from .env)
"""
import json
import os
import subprocess
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path

from src.config import ROOT

SOURCES = ("products", "carts", "users")


def make_extracts(data_dir: Path, with_xlsx: bool = False) -> None:
    for name in SOURCES:
        d = data_dir / "raw" / name
        d.mkdir(parents=True, exist_ok=True)
        (d / f"{name}_20990101T000000Z.json").write_text(
            json.dumps({"total": 2, name: [{"id": 1, "drill": True}, {"id": 2, "drill": True}]}))
    if with_xlsx:
        (data_dir / "raw" / "online_retail_II.xlsx").write_bytes(b"placeholder")


def run(module: str, data_dir: Path, **extra_env) -> subprocess.CompletedProcess:
    env = {**os.environ, "DATA_DIR": str(data_dir), **extra_env}
    return subprocess.run([sys.executable, "-m", module], cwd=ROOT, env=env, capture_output=True, text=True)


def audit(data_dir: Path) -> list[dict]:
    p = data_dir / "audit" / "ingestion_log.jsonl"
    return [json.loads(x) for x in p.read_text().splitlines()] if p.exists() else []


def main() -> int:
    bucket = os.environ.get("S3_BUCKET")
    if not bucket:
        sys.exit("S3_BUCKET is not set (check .env)")
    results = []

    def record(name, expected, ok, detail):
        results.append((name, expected, "PASS" if ok else "FAIL", detail))
        print(f"{name}: {'PASS' if ok else 'FAIL'} - {detail}")

    with tempfile.TemporaryDirectory() as t1, tempfile.TemporaryDirectory() as t2, \
            tempfile.TemporaryDirectory() as t3:
        # D1
        r = run("ingestion.validate_extracts", Path(t1))
        record("D1 missing extracts", "validation fails (exit 1)", r.returncode == 1,
               f"exit {r.returncode}; " + "; ".join(l.replace("VALIDATION FAILED: ", "") for l in r.stdout.splitlines()[:2]))
        # D2
        make_extracts(Path(t2), with_xlsx=True)
        r = run("ingestion.validate_extracts", Path(t2))
        record("D2 valid extracts", "validation passes (exit 0)", r.returncode == 0, f"exit {r.returncode}; {r.stdout.strip()}")
        # D3
        dd = Path(t3)
        make_extracts(dd)
        env = {"S3_PREFIX": "archive/drill"}
        r = run("ingestion.upload_to_s3", dd, S3_BUCKET=f"{bucket}-drill-does-not-exist", **env)
        a = audit(dd)
        record("D3 upload to bad bucket", "upload fails, audit status=failed",
               r.returncode != 0 and any(x["status"] == "failed" for x in a),
               f"exit {r.returncode}; audit statuses {[x['status'] for x in a]}")
        # D4
        r = run("ingestion.upload_to_s3", dd, S3_BUCKET=bucket, **env)
        a = audit(dd)
        up = [x for x in a if x["status"] == "uploaded"]
        record("D4 recovery run", "3 files uploaded after fixing the bucket",
               r.returncode == 0 and len(up) == 3, f"exit {r.returncode}; uploaded {len(up)} files, keys under {env['S3_PREFIX']}/")
        # D5
        n_before = len(a)
        r = run("ingestion.upload_to_s3", dd, S3_BUCKET=bucket, **env)
        new = audit(dd)[n_before:]
        record("D5 idempotent rerun", "all files skipped_duplicate, nothing re-uploaded",
               r.returncode == 0 and len(new) == 3 and all(x["status"] == "skipped_duplicate" for x in new),
               f"exit {r.returncode}; statuses {[x['status'] for x in new]}")
        sample = [{k: x[k] for k in ("source", "rows", "sha256", "status")} | {"sha256": x["sha256"][:12] + "..."}
                  for x in audit(dd)]

    ts = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines = [f"# Failure and recovery evidence", "", f"Generated by `scripts/failure_drill.py` on {ts}.",
             "Isolated temp data dir; S3 test objects only under `archive/drill/`.", "",
             "| Scenario | Expected | Result | Detail |", "|---|---|---|---|"]
    lines += [f"| {n} | {e} | **{r}** | {d} |" for n, e, r, d in results]
    lines += ["", "## Audit log from the drill (D3-D5)", "", "```"] + [json.dumps(s) for s in sample] + ["```"]
    (ROOT / "docs" / "failure_recovery_evidence.md").write_text("\n".join(lines) + "\n")
    print("Wrote docs/failure_recovery_evidence.md")
    return 0 if all(r[2] == "PASS" for r in results) else 1


if __name__ == "__main__":
    sys.exit(main())
